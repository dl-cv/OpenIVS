"""Freeze Python Unicode casing used by category_block for both runtimes."""
import json
from pathlib import Path
import unicodedata


def ranges(values):
    result = []
    for value in values:
        if result and value == result[-1][1] + 1:
            result[-1][1] = value
        else:
            result.append([value, value])
    return result


def main():
    if unicodedata.unidata_version != '14.0.0':
        raise RuntimeError('Use Python Unicode 14.0.0, matching the reference runtime')
    chars = [chr(i) for i in range(0x110000)]
    data = {
        'version': unicodedata.unidata_version,
        'lower': {str(ord(c)): [ord(x) for x in c.lower()] for c in chars if c.lower() != c},
        'space': ranges(ord(c) for c in chars if c.isspace()),
        'cased': ranges(ord(c) for c in chars if c.islower() or c.isupper() or c.istitle()),
        # Python's final-sigma context skips Case_Ignorable, even if also Cased.
        'ignorable': ranges(ord(c) for c in chars if ('A' + c + 'Σ').lower().endswith('ς')
                            and ('AΣ' + c).lower()[1] == 'ς'
                            and ('AΣ' + c + 'A').lower()[1] == 'σ'),
    }
    root = Path(__file__).resolve().parents[1]
    text = json.dumps(data, separators=(',', ':'))
    target = root / 'DlcvCsharpApi/flow/modules/CategoryBlockUnicode.json'
    target.write_text(text + '\n', encoding='utf-8')
    header = root / 'dlcv_infer_cpp/flow/utils/CategoryBlockUnicode.h'
    header.write_text('// Generated by build_script/generate_category_unicode.py; Unicode 14.0.0.\n'
                      '#pragma once\nstatic constexpr const char* CategoryBlockUnicodeData =\n'
                      + '\n'.join(json.dumps(text[i:i+1000]) for i in range(0, len(text), 1000))
                      + ';\n', encoding='utf-8')
    print(f'Unicode data: {len(text)} bytes per runtime')


if __name__ == '__main__':
    main()
